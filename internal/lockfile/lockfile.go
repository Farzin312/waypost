package lockfile

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/Farzin312/waypost/internal/config"
	"github.com/Farzin312/waypost/internal/version"
	"gopkg.in/yaml.v3"
)

const LockFileName = ".waypost.lock"

// Lockfile pins inheritance ancestors, effective digests, and execution authorization
// state so CI runs deterministically and offline without implicit script activation.
type Lockfile struct {
	LockVersion     string                   `yaml:"lock_version" json:"lock_version"`
	SchemaVersion   string                   `yaml:"schema_version" json:"schema_version"`
	ResolverVersion string                   `yaml:"resolver_version" json:"resolver_version"`
	ConfigSHA256    string                   `yaml:"config_sha256" json:"config_sha256"`
	PolicyDigest    string                   `yaml:"policy_digest" json:"policy_digest"`
	Chain           []config.InheritanceStep `yaml:"chain,omitempty" json:"chain,omitempty"`
	Skills          []LockedSkill            `yaml:"skills,omitempty" json:"skills,omitempty"`
	Providers       []LockedProvider         `yaml:"providers,omitempty" json:"providers,omitempty"`
}

// LockedSkill pins an external skill reference and its explicit authorization bit.
type LockedSkill struct {
	ID         string `yaml:"id" json:"id"`
	Source     string `yaml:"source" json:"source"`
	Version    string `yaml:"version,omitempty" json:"version,omitempty"`
	Kind       string `yaml:"kind,omitempty" json:"kind,omitempty"`
	Authorized bool   `yaml:"authorized" json:"authorized"`
}

// LockedProvider pins an external tool provider command and its authorization bit.
type LockedProvider struct {
	ID         string `yaml:"id" json:"id"`
	Tool       string `yaml:"tool" json:"tool"`
	Command    string `yaml:"command" json:"command"`
	Authorized bool   `yaml:"authorized" json:"authorized"`
}

// VerifyResult summarizes lockfile integrity and any detected drift or permission escalations.
type VerifyResult struct {
	Present                 bool     `json:"present"`
	Valid                   bool     `json:"valid"`
	LockDigest              string   `json:"lock_digest"`
	Mismatches              []string `json:"mismatches,omitempty"`
	AuthorizationEscalation []string `json:"authorization_escalation,omitempty"`
}

// Generate constructs a Lockfile from a ResolvedConfig.
// Note: callers generating a lockfile for commits should pass a ResolvedConfig
// loaded in "ci" mode so .waypost.local.yaml never pollutes the committed lockfile.
func Generate(res *config.ResolvedConfig) Lockfile {
	lf := Lockfile{
		LockVersion:     "1",
		SchemaVersion:   version.SchemaVersion,
		ResolverVersion: version.ResolverVersion,
		ConfigSHA256:    res.RawRootSHA256,
		PolicyDigest:    res.PolicyDigest,
		Chain:           append([]config.InheritanceStep(nil), res.Chain...),
	}
	for _, s := range res.Effective.Skills {
		lf.Skills = append(lf.Skills, LockedSkill{
			ID:         s.ID,
			Source:     s.Source,
			Version:    s.Version,
			Kind:       s.Kind,
			Authorized: s.Authorized,
		})
	}
	for _, p := range res.Effective.Providers {
		lf.Providers = append(lf.Providers, LockedProvider{
			ID:         p.ID,
			Tool:       p.Tool,
			Command:    p.Command,
			Authorized: p.Authorized,
		})
	}
	return lf
}

// Marshal serializes a Lockfile to deterministic YAML bytes.
func Marshal(lf Lockfile) ([]byte, error) {
	out, err := yaml.Marshal(&lf)
	if err != nil {
		return nil, fmt.Errorf("marshal lockfile: %w", err)
	}
	header := "# Generated by waypost. Commit this file for frozen, offline CI verification.\n"
	return append([]byte(header), out...), nil
}

// Write writes <repoDir>/.waypost.lock atomically and returns its SHA-256 digest.
func Write(repoDir string, lf Lockfile) (string, error) {
	b, err := Marshal(lf)
	if err != nil {
		return "", err
	}
	path := filepath.Join(repoDir, LockFileName)
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil {
		return "", fmt.Errorf("write lockfile tmp: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return "", fmt.Errorf("rename lockfile: %w", err)
	}
	return sha256Hex(b), nil
}

// Read parses <repoDir>/.waypost.lock and returns the Lockfile plus its raw SHA-256 digest.
func Read(repoDir string) (*Lockfile, string, error) {
	path := filepath.Join(repoDir, LockFileName)
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, "", err
	}
	var lf Lockfile
	dec := yaml.NewDecoder(strings.NewReader(string(b)))
	dec.KnownFields(true)
	if err := dec.Decode(&lf); err != nil {
		return nil, "", fmt.Errorf("parse %s: %w", path, err)
	}
	return &lf, sha256Hex(b), nil
}

// Verify checks <repoDir>/.waypost.lock against the currently resolved config (without local overrides).
func Verify(repoDir string, canonicalRes *config.ResolvedConfig) VerifyResult {
	lf, digest, err := Read(repoDir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return VerifyResult{
				Present:    false,
				Valid:      false,
				Mismatches: []string{fmt.Sprintf("%s is missing; run `waypost upgrade --apply` or `waypost init`", LockFileName)},
			}
		}
		return VerifyResult{
			Present:    true,
			Valid:      false,
			Mismatches: []string{err.Error()},
		}
	}

	res := VerifyResult{
		Present:    true,
		Valid:      true,
		LockDigest: digest,
	}

	if lf.LockVersion != "1" {
		res.Mismatches = append(res.Mismatches, fmt.Sprintf("unsupported lock_version %q", lf.LockVersion))
	}
	if lf.ResolverVersion != version.ResolverVersion {
		res.Mismatches = append(res.Mismatches, fmt.Sprintf("resolver_version mismatch: lock=%q current=%q", lf.ResolverVersion, version.ResolverVersion))
	}
	if lf.ConfigSHA256 != canonicalRes.RawRootSHA256 {
		res.Mismatches = append(res.Mismatches, fmt.Sprintf(".waypost.yaml sha256 mismatch: lock=%s current=%s", shortHash(lf.ConfigSHA256), shortHash(canonicalRes.RawRootSHA256)))
	}
	if lf.PolicyDigest != canonicalRes.PolicyDigest {
		res.Mismatches = append(res.Mismatches, fmt.Sprintf("effective policy digest mismatch: lock=%s current=%s", shortHash(lf.PolicyDigest), shortHash(canonicalRes.PolicyDigest)))
	}

	// Verify inheritance chain
	if len(lf.Chain) != len(canonicalRes.Chain) {
		res.Mismatches = append(res.Mismatches, fmt.Sprintf("inheritance chain length changed: lock=%d current=%d", len(lf.Chain), len(canonicalRes.Chain)))
	} else {
		for i := range lf.Chain {
			if lf.Chain[i].Ref != canonicalRes.Chain[i].Ref || lf.Chain[i].SHA256 != canonicalRes.Chain[i].SHA256 {
				res.Mismatches = append(res.Mismatches, fmt.Sprintf("ancestor %d changed: lock=(%s %s) current=(%s %s)",
					i, lf.Chain[i].Ref, shortHash(lf.Chain[i].SHA256), canonicalRes.Chain[i].Ref, shortHash(canonicalRes.Chain[i].SHA256)))
			}
		}
	}

	// Detect authorization escalations on skills and providers.
	lockedSkills := make(map[string]LockedSkill, len(lf.Skills))
	for _, s := range lf.Skills {
		lockedSkills[s.ID] = s
	}
	for _, s := range canonicalRes.Effective.Skills {
		prev, ok := lockedSkills[s.ID]
		if s.Authorized && (!ok || !prev.Authorized) {
			res.AuthorizationEscalation = append(res.AuthorizationEscalation, fmt.Sprintf("skill %q newly authorized", s.ID))
		}
	}

	lockedProvs := make(map[string]LockedProvider, len(lf.Providers))
	for _, p := range lf.Providers {
		lockedProvs[p.ID] = p
	}
	for _, p := range canonicalRes.Effective.Providers {
		prev, ok := lockedProvs[p.ID]
		if p.Authorized && (!ok || !prev.Authorized || prev.Command != p.Command) {
			res.AuthorizationEscalation = append(res.AuthorizationEscalation, fmt.Sprintf("provider %q newly authorized or command changed", p.ID))
		}
	}

	if len(res.Mismatches) > 0 || len(res.AuthorizationEscalation) > 0 {
		res.Valid = false
	}
	return res
}

func sha256Hex(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

func shortHash(h string) string {
	if len(h) > 12 {
		return h[:12]
	}
	return h
}
